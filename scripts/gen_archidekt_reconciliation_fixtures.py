def card(index: int, name: str, categories: list, qty: int = 1,
         types: list | None = None, finish: str | None = None,
         owned: str | None = None):
    return {
        "quantity": qty,
        "categories": categories,
        **({"finish": finish} if finish else {}),
        **({"owned": owned} if owned else {}),
        "card": {
            "uid": f"sf-fx-{index:04d}",
            "collectorNumber": str(index),
            "rarity": "rare",
            "edition": {"editioncode": "fx"},
            "prices": {"usd": 0.25},
            "oracleCard": {
                "name": name,
                "uid": f"o-fx-{index:04d}",
                "types": types or ["Creature"],
                "superTypes": [],
                "subTypes": [],
                "cmc": 3.0,
                "manaCost": "{2}{G}",
                "colors": ["Green"],
                "colorIdentity": ["Green"],
                "text": "",
                "keywords": [],
            },
        },
    }


def deck(source_id: int, name: str, cards: list, categories: list,
         updated_at: str):
    return {
        "id": source_id,
        "name": name,
        "parentFolderId": 588380,
        "parentFolderName": "Commander Decks",
        "deckFormat": 3,
        "updatedAt": updated_at,
        "createdAt": "2024-01-01T00:00:00Z",
        "description": "",
        "categories": categories,
        "cards": cards,
        "_fixture_note": NOTE,
    }


def aragorn():
    """92 rows / 100 units, every unit in included categories (SRC-02)."""
    cards = [
        card(1, "Aragorn, the Uniter", ["Commander"], 1,
             types=["Legendary", "Creature"], finish="foil", owned="Have"),
    ]
    i = 2
    for n in range(83):  # qty 1 rows: 83
        cards.append(card(i, f"Fixture Card {i:03d}", ["Maindeck"], 1,
                          finish="nonfoil"))
        i += 1
    for n in range(8):  # qty 2 rows: 8 rows -> 16 units
        cards.append(card(i, f"Fixture Card {i:03d}", ["Ramp"], 2))
        i += 1
    assert len(cards) == 92
