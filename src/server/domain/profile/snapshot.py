"""Profile snapshot computation — pure functions over plain dicts.

Inputs (fetched by the caller, e.g. workers/importer.py or an API router):

    deck:       {"id", "name", "commanders": [str], "color_identity": [str]}
    deck_cards: repository rows [{"oracle_id", "name", "board", "qty",
                                  "category", "type_line", "cmc", "colors"}]
    have_buy:   the output of domain.inventory.have_buy.compute_have_buy

Output (stored verbatim on a profile_snapshots row):

    inputs:  what the metrics were computed from (provenance, no card data)
    metrics: {"curve": {...}, "archetype_mix": {...}, "ownership": {...}}
    summary_text: plain-language summary, generated by string templates —
                  numbers and labels are deterministic code (AGENT_RULES §5).

Curve: mana curve of non-land spells in the playable boards (commander+main),
bucketed 0..6 and 7+, matching the legacy deck page's renderStats bucketing
(min(floor(cmc), 7), lands excluded by type_line). Cards with a NULL cmc are
reported as "unavailable" (AGENT_RULES §4), never counted as 0.

Archetype mix: distribution of the deck's non-structural categories (the
Archidekt/user role labels preserved on import — Ramp, Card Draw, Removal…).
Structural categories are excluded per AGENT_RULES §9. Cards without a
category fall under "Uncategorized".
"""
from __future__ import annotations

REQUIREMENT_BOARDS = ("commander", "main")
CURVE_BUCKETS = ("0", "1", "2", "3", "4", "5", "6", "7+")


def _is_land(type_line) -> bool:
    return "land" in (type_line or "").lower()


def _curve(deck_cards: list) -> dict:
    spells = [c for c in deck_cards
              if c.get("board") in REQUIREMENT_BOARDS and not _is_land(c.get("type_line"))]
    lands = [c for c in deck_cards
             if c.get("board") in REQUIREMENT_BOARDS and _is_land(c.get("type_line"))]
    buckets = {b: 0 for b in CURVE_BUCKETS}
    unavailable = 0
    cmc_sum = 0.0
    for c in spells:
        cmc = c.get("cmc")
        qty = int(c.get("qty") or 1)
        if cmc is None:
            unavailable += qty
            continue
        cmc_sum += cmc * qty
        buckets["7+" if cmc >= 7 else str(int(cmc))] += qty
    spell_count = sum(int(c.get("qty") or 1) for c in spells)
    known = spell_count - unavailable
    return {
        "buckets": buckets,
        "spell_count": spell_count,
        "land_count": sum(int(c.get("qty") or 1) for c in lands),
        "avg_cmc": round(cmc_sum / known, 2) if known else None,
        "unavailable_cmc_count": unavailable,
    }


def _archetype_mix(deck_cards: list) -> dict:
    counts: dict = {}
    total = 0
    for c in deck_cards:
        if c.get("board") not in REQUIREMENT_BOARDS:
            continue
        qty = int(c.get("qty") or 1)
        label = (c.get("category") or "").strip() or "Uncategorized"
        counts[label] = counts.get(label, 0) + qty
        total += qty
    mix = [
        {"category": k, "count": v, "share": round(v / total, 3) if total else 0.0}
        for k, v in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))
    ]
    return {"total_cards": total, "mix": mix}


def _colors(deck: dict, deck_cards: list) -> dict:
    counts = {c: 0 for c in "WUBRG"}
    for c in deck_cards:
        if c.get("board") not in REQUIREMENT_BOARDS or _is_land(c.get("type_line")):
            continue
        qty = int(c.get("qty") or 1)
        for color in (c.get("colors") or []):
            if color in counts:
                counts[color] += qty
    return {k: v for k, v in counts.items() if v}


def compute_metrics(deck: dict, deck_cards: list, have_buy: dict) -> dict:
    """The metrics blob stored on the snapshot row."""
    return {
        "curve": _curve(deck_cards),
        "archetype_mix": _archetype_mix(deck_cards),
        "color_pip_counts": _colors(deck, deck_cards),
        "ownership": have_buy.get("totals", {}),
    }


def build_inputs(deck: dict, trigger: str) -> dict:
    """Provenance for the metrics — what went in, no card data duplicated."""
    return {
        "trigger": trigger,
        "deck_id": deck.get("id"),
        "deck_name": deck.get("name"),
        "commanders": list(deck.get("commanders") or []),
    }


def _fmt_colors(color_identity: list) -> str:
    if not color_identity:
        return "colorless"
    return "/".join(color_identity)


def render_summary(deck: dict, metrics: dict) -> str:
    """Plain-language summary text, generated deterministically from the
    metrics blob (template strings only — rule: if the LLM could have made it
    up, it doesn't ship)."""
    curve = metrics["curve"]
    mix = metrics["archetype_mix"]["mix"]
    ownership = metrics.get("ownership") or {}

    parts = []
    commanders = deck.get("commanders") or []
    led_by = f" led by {', '.join(commanders)}" if commanders else ""
    parts.append(
        f"{deck.get('name', 'This deck')} is a {_fmt_colors(deck.get('color_identity') or [])} "
        f"deck{led_by} with {curve['land_count']} lands and {curve['spell_count']} spells."
    )
    if curve["avg_cmc"] is not None:
        peak_n = max(curve["buckets"].values()) if any(curve["buckets"].values()) else 0
        peaks = [b for b, n in curve["buckets"].items() if n == peak_n and peak_n]
        lean = ("low to the ground" if curve["avg_cmc"] < 2.5
                else "midrange" if curve["avg_cmc"] < 4.0 else "top-heavy")
        parts.append(
            f"Its curve is {lean}: average spell cost {curve['avg_cmc']:.2f}, "
            f"peaking at {peak_n} card{'s' if peak_n != 1 else ''} in the "
            f"{'/'.join(peaks)} slot{'s' if len(peaks) != 1 else ''}."
        )
    if curve["unavailable_cmc_count"]:
        parts.append(
            f"Mana cost unavailable for {curve['unavailable_cmc_count']} card "
            f"copies (not counted in the curve)."
        )
    top = [m for m in mix if m["category"] != "Uncategorized"][:3]
    if top:
        roles = ", ".join(f"{m['category']} ({m['count']})" for m in top)
        parts.append(f"Main roles: {roles}.")
    uncategorized = next((m for m in mix if m["category"] == "Uncategorized"), None)
    if uncategorized:
        parts.append(f"{uncategorized['count']} cards have no role tag yet.")
    required = ownership.get("required")
    if required:
        have, buy = ownership.get("have", 0), ownership.get("buy", 0)
        pending = ownership.get("pending", 0)
        line = f"You have {have} of {required} cards"
        if pending:
            line += f", {pending} on the way"
        line += f" — {buy} to buy." if buy else " — nothing to buy."
        parts.append(line)
    return " ".join(parts)
